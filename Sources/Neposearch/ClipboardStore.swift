import AppKit
import ObjectBox
import Observation

/// Sleduje systémovú schránku a ukladá históriu do ObjectBoxu.
@MainActor @Observable
final class ClipboardStore {
    static let maxItems = 1000
    static let maxAge: TimeInterval = 90 * 24 * 3600

    /// Počet položiek – mení sa pri každej zmene histórie (aby sa zoznam v UI obnovil).
    private(set) var revision = 0

    @ObservationIgnored private let box: Box<ClipboardItem>
    @ObservationIgnored private let settings: AppSettings
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChangeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private let imagesDirectory: URL

    /// Typy, ktorými správcovia hesiel a systém označujú obsah, ktorý sa nemá ukladať.
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]

    init(database: Database, settings: AppSettings) {
        box = database.store.box(for: ClipboardItem.self)
        self.settings = settings
        imagesDirectory = Database.defaultDirectory.deletingLastPathComponent().appendingPathComponent("clipboard", isDirectory: true)
        try? FileManager.default.createDirectory(at: imagesDirectory, withIntermediateDirectories: true)
        prune()
        updateMonitoring()
    }

    func updateMonitoring() {
        timer?.invalidate()
        timer = nil
        guard settings.clipboardEnabled else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
    }

    // MARK: - Zachytenie

    private func check() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }
        let source = NSWorkspace.shared.frontmostApplication
        // Vlastné kopírovanie (napr. „Kopírovať cestu“) ukladáme tiež, zdroj je vtedy Neposearch.

        let item = ClipboardItem()
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
            !urls.isEmpty
        {
            item.kind = ClipboardKind.files.rawValue
            item.text = urls.map(\.path).joined(separator: "\n")
        } else if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            item.kind = ClipboardKind.text.rawValue
            item.text = text
        } else if let image = NSImage(pasteboard: pasteboard), let png = Self.pngData(image) {
            let url = imagesDirectory.appendingPathComponent("\(UUID().uuidString).png")
            guard (try? png.write(to: url)) != nil else { return }
            item.kind = ClipboardKind.image.rawValue
            item.imagePath = url.path
            item.text = "\(Int(image.size.width))×\(Int(image.size.height))"
        } else {
            return
        }
        item.sourceAppName = source?.localizedName ?? ""
        item.sourceAppPath = source?.bundleURL?.path ?? ""
        item.createdAt = Date()
        item.searchKey = IndexedFile.normalize("\(item.text) \(item.sourceAppName)")
        save(item)
    }

    /// Rovnaký text sa neukladá dvakrát – existujúca položka sa len posunie navrch.
    private func save(_ item: ClipboardItem) {
        if item.clipKind != .image,
            let existing = try? box.query({ ClipboardItem.text == item.text && ClipboardItem.kind == item.kind }).build().findFirst()
        {
            existing.createdAt = item.createdAt
            existing.sourceAppName = item.sourceAppName
            existing.sourceAppPath = item.sourceAppPath
            _ = try? box.put(existing)
        } else {
            _ = try? box.put(item)
        }
        revision += 1
        if revision % 50 == 0 { prune() }
    }

    private static func pngData(_ image: NSImage) -> Data? {
        guard let tiff = image.tiffRepresentation, let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    // MARK: - Hľadanie

    /// Pripnuté navrchu, potom najnovšie. Pri dotaze musí položka obsahovať všetky slová.
    func items(matching query: String, limit: Int = 50) -> [ClipboardItem] {
        _ = revision
        let words = IndexedFile.normalize(query).split(whereSeparator: \.isWhitespace).map(String.init)
        let builder: QueryBuilder<ClipboardItem>
        if let first = words.first {
            builder = box.query {
                words.dropFirst().reduce(ClipboardItem.searchKey.contains(first) as QueryCondition<ClipboardItem>) {
                    $0 && ClipboardItem.searchKey.contains($1)
                }
            }
        } else {
            builder = box.query()
        }
        let found = (try? builder.ordered(by: ClipboardItem.createdAt, flags: .descending).build().find(offset: 0, limit: limit)) ?? []
        return found.filter(\.isPinned) + found.filter { !$0.isPinned }
    }

    // MARK: - Akcie

    /// Vloží položku do schránky (bez toho, aby sa uložila ako nová).
    func copyToPasteboard(_ item: ClipboardItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.clipKind {
        case .text:
            pasteboard.setString(item.text, forType: .string)
        case .files:
            pasteboard.writeObjects(item.fileURLs as [NSURL])
        case .image:
            if let image = NSImage(contentsOfFile: item.imagePath) { pasteboard.writeObjects([image]) }
        }
        lastChangeCount = pasteboard.changeCount
        item.createdAt = Date()
        _ = try? box.put(item)
        revision += 1
    }

    /// Vloží položku do aktívnej aplikácie (⌘V). Bez povolenia Accessibility ju len skopíruje.
    /// - Returns: `true`, ak sa vložila; `false`, ak sa len skopírovala.
    @discardableResult
    func paste(_ item: ClipboardItem, into app: NSRunningApplication?) -> Bool {
        copyToPasteboard(item)
        guard AXIsProcessTrusted() else { return false }
        app?.activate()
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) {
            let source = CGEventSource(stateID: .combinedSessionState)
            let keyV: CGKeyCode = 9
            let down = CGEvent(keyboardEventSource: source, virtualKey: keyV, keyDown: true)
            let up = CGEvent(keyboardEventSource: source, virtualKey: keyV, keyDown: false)
            down?.flags = .maskCommand
            up?.flags = .maskCommand
            down?.post(tap: .cghidEventTap)
            up?.post(tap: .cghidEventTap)
        }
        return true
    }

    func togglePin(_ item: ClipboardItem) {
        item.isPinned.toggle()
        _ = try? box.put(item)
        revision += 1
    }

    func delete(_ item: ClipboardItem) {
        if !item.imagePath.isEmpty { try? FileManager.default.removeItem(atPath: item.imagePath) }
        _ = try? box.remove(item.id)
        revision += 1
    }

    /// Vymaže celú históriu okrem pripnutých položiek.
    func clearHistory() {
        let unpinned = (try? box.query { ClipboardItem.isPinned == false }.build().find()) ?? []
        unpinned.forEach { if !$0.imagePath.isEmpty { try? FileManager.default.removeItem(atPath: $0.imagePath) } }
        _ = try? box.remove(unpinned.map(\.id))
        revision += 1
    }

    var count: Int { _ = revision; return (try? box.count()) ?? 0 }

    /// Necháme najviac 1000 nepripnutých položiek, nie staršie ako 90 dní.
    private func prune() {
        let unpinned = (try? box.query { ClipboardItem.isPinned == false }
            .ordered(by: ClipboardItem.createdAt, flags: .descending).build().find()) ?? []
        let cutoff = Date().addingTimeInterval(-Self.maxAge)
        let old = unpinned.enumerated().filter { $0.offset >= Self.maxItems || $0.element.createdAt < cutoff }.map(\.element)
        guard !old.isEmpty else { return }
        old.forEach { if !$0.imagePath.isEmpty { try? FileManager.default.removeItem(atPath: $0.imagePath) } }
        _ = try? box.remove(old.map(\.id))
    }
}
